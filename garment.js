/* 影の型。布の左に落ちる影と、右からの反射を 1 枚で済ませます。
   instance ごとに id を変えないと、同じ画面に複数置いたとき
   最初のグラデーションが全部に効いてしまいます。 */
let gradSeq = 0;

/**
 * 服の絵を SVG 文字列で返します。
 * look = { top, outer, bottom, shoe, hat, colors: { top, outer, bottom, shoe, hat } }
 * colors は 16 進。'none' を指した部位の色は読みません。
 * hat は省略できます（省略時は被りません）。
 */
function garmentSVG(look, opts = {}) {
  const gid = 'gsh' + (++gradSeq);
  const label = opts.label || '着装図';

  const tops    = TOPS[look.top]       || TOPS.tee;
  const outers  = OUTERS[look.outer]   || OUTERS.none;
  const bottoms = BOTTOMS[look.bottom] || BOTTOMS.slim;
  const shoes   = SHOES[look.shoe]     || SHOES.low;
  const hats    = HATS[look.hat || 'none'] || HATS.none;

  // 輪郭。太いほど図案に、細いほど図面に寄ります。
  const paint = (paths, fill) =>
    paths.map(d => `<path d="${d}" fill="${fill}" stroke="#14141a" stroke-width="1.9"`
      + ` stroke-linejoin="round" stroke-linecap="round"/>`).join('');

  // 線だけのパーツ。輪郭より細くしないと、縫い目が輪郭に見えます。
  const draw = (paths) =>
    paths.map(d => `<path d="${d}" fill="none" stroke="#14141a" stroke-width="1.05"`
      + ` stroke-linecap="round" stroke-linejoin="round" opacity=".62"/>`).join('');

  // 影は色を持たず、下の面をそのまま暗くします。
  const shade = (paths) =>
    paths.map(d => `<path d="${d}" fill="url(#${gid})" stroke="none"/>`).join('');

  const det = (cat, name) => (DETAILS[cat] && DETAILS[cat][name]) || [];

  const garments = [...bottoms, ...shoes, ...tops, ...outers, ...hats];

  return `
<svg class="garment" viewBox="${VIEW_BOX}" role="img" aria-label="${label}" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="${gid}" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0"   stop-color="#000" stop-opacity=".16"/>
      <stop offset=".32" stop-color="#000" stop-opacity="0"/>
      <stop offset=".78" stop-color="#000" stop-opacity="0"/>
      <stop offset="1"   stop-color="#000" stop-opacity=".10"/>
    </linearGradient>
  </defs>

  <!-- 1. 体。服より先に置きます -->
  ${paint(BODY, 'var(--form, #d8d2c4)')}

  <!-- 2. 下 → 3. 足元 → 4. 上 → 5. 羽織り → 6. 帽子
       それぞれ、面を塗った直後にその部位の線を引きます。あとで
       まとめて引くと、上に重なる服の下から縫い目が透けます。 -->
  ${paint(bottoms, look.colors.bottom)}${draw(det('bottom', look.bottom))}
  ${paint(shoes,   look.colors.shoe)}${draw(det('shoe', look.shoe))}
  ${paint(tops,    look.colors.top)}${draw(det('top', look.top))}
  ${outers.length ? paint(outers, look.colors.outer) + draw(det('outer', look.outer)) : ''}
  ${hats.length   ? paint(hats,   look.colors.hat)   + draw(det('hat', look.hat))     : ''}

  <!-- 7. 影を一枚。multiply なので、下の色を選び直しても効き方は変わりません -->
  <g style="mix-blend-mode:multiply">${shade(garments)}</g>
</svg>`;
}
